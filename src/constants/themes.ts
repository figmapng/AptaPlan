export const THEME_LIST: ThemeConfig[] = Object.values(THEMES);

export type AppColors = ColorPalette & {
  primary: string;
  primaryDark: string;
  tintBg: string;
};

export function getThemeColors(themeId?: ThemeId, isDark: boolean = false): AppColors {
  const theme = (themeId && THEMES[themeId]) ? THEMES[themeId] : THEMES.ocean;

  if (isDark) {
    if (theme.id === 'minimal') {
      return {
        ...darkColors,
        primary: '#E4E4E7',
        primaryDark: '#D4D4D8',
        today: '#E4E4E7',
        todayDark: '#A1A1AA',
        activeHeaderBg: '#3F485A',
        activeCardBorder: '#A1A1AA',
        activeHeaderText: '#FFFFFF',
        inputFocusedBorder: '#A1A1AA',
        inputCursor: '#E4E4E7',
        inputPlusIcon: '#E4E4E7',
        tintBg: 'rgba(255, 255, 255, 0.08)',
        chipBg: darkColors.inputBg,
        chipBorder: darkColors.inputBorder,
        chipText: darkColors.text,
        chipActiveText: '#FFFFFF',
      };
    }

    if (theme.id === 'slate') {
      return {
        ...darkColors,
        primary: '#94A3B8',
        primaryDark: '#64748B',
        today: '#94A3B8',
        todayDark: '#64748B',
        activeHeaderBg: '#94A3B8',
        activeCardBorder: '#94A3B8',
        activeHeaderText: '#0F172A',
        inputFocusedBorder: '#94A3B8',
        inputCursor: '#94A3B8',
        inputPlusIcon: '#94A3B8',
        tintBg: 'rgba(148, 163, 184, 0.15)',
        chipBg: darkColors.inputBg,
        chipBorder: darkColors.inputBorder,
        chipText: darkColors.text,
        chipActiveText: '#F3F5F9',
      };
    }

    return {
      ...darkColors,
      primary: theme.primary,
      primaryDark: theme.primaryDark,
      tintBg: `${theme.today}1A`,
      today: theme.today,
      todayDark: theme.todayDark,
      activeHeaderBg: theme.today,
      activeCardBorder: theme.today,
      activeHeaderText: '#FFFFFF',
      inputFocusedBorder: theme.today,
      inputCursor: theme.today,
      inputPlusIcon: theme.primary,
      chipBg: darkColors.inputBg,
      chipBorder: darkColors.inputBorder,
      chipText: darkColors.text,
      chipActiveText: '#F3F5F9',
    };
  }

  return {
    ...lightColors,
    background: theme.background,
    primary: theme.primary,
    primaryDark: theme.primaryDark,
    tintBg: theme.tintBg,
    today: theme.today,
    todayDark: theme.todayDark,
    activeHeaderBg: theme.activeHeaderBg,
    activeCardBorder: theme.activeCardBorder,
    activeHeaderText: theme.activeHeaderText,
    inputFocusedBorder: theme.inputFocusedBorder,
    inputCursor: theme.inputCursor,

    // Hue-harmonized chromatic neutrals
    inputBg: theme.inputBg,
    inputBorder: theme.inputBorder,
    cardHeaderBg: theme.cardHeaderBg,
    cardBorder: theme.cardBorder,
    dateNumBg: theme.dateNumBg,
    dateNumText: theme.dateNumText,
    capsule: theme.capsule,
    text: theme.text,
    secondary: theme.secondary,
    inputPlaceholder: theme.inputPlaceholder,
    inputPlusIcon: theme.inputPlusIcon,
    checkboxBorder: theme.checkboxBorder,
    checkedCheckboxBg: theme.checkedCheckboxBg,
    checkedTaskText: theme.secondary,
    divider: theme.divider,

    // Chip tokens harmonized with active theme
    chipBg: theme.inputBg,
    chipBorder: theme.inputBorder,
    chipText: theme.text,
  };
}
